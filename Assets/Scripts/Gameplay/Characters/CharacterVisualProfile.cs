using UnityEngine;

namespace WarOfNyx.Gameplay.Characters
{
    /// <summary>
    /// What a skinned character looks like: its runtime prefab (skinned meshes, skeleton, Animator with the humanoid
    /// Avatar), the facial setup and the supernatural energy colour. One asset per character, loaded by
    /// <see cref="SkinnedCharacterLoader"/> from Resources/WarOfNyx/Characters/{NAME}.
    /// </summary>
    [CreateAssetMenu(menuName = "War of Nyx/Character Visual Profile")]
    public sealed class CharacterVisualProfile : ScriptableObject
    {
        public string characterName = "KAI";
        public GameObject prefab;
        public CharacterAnimationProfile animation;
        public Color energyColor = new Color(0.62f, 0.25f, 1f);
        [Tooltip("Height of the head centre above the feet (character preview framing).")]
        public float headHeight = 1.69f;
        [Tooltip("Submesh index of the painted face on the skinned renderers.")]
        public int faceSubmesh = 1;
        [Tooltip("Origin of the art: Procedural (generated by the setup step) or Imported (artist-made FBX / VRM / glTF).")]
        public string artSource = "Procedural";
        [Tooltip("Attribution shown on the CHARACTERS screen (required by CC-BY licences): title, author, licence, source.")]
        public string credit = string.Empty;
        [Tooltip("When the model replaces a roster look: description lines shown instead of the roster's (empty = roster text).")]
        public string titleOverride = string.Empty;
        public string storyOverride = string.Empty;
        public string[] gearOverride = new string[0];
    }
}
