using System;
using UnityEngine;

namespace WarOfNyx.Gameplay.Characters
{
    /// <summary>A chain of helper bones (hair lock, coat tail, ribbon) simulated by <see cref="CharacterSecondaryMotion"/>.</summary>
    [Serializable]
    public sealed class SpringChainDef
    {
        [Tooltip("Bone names from the root of the chain to its tip.")]
        public string[] bones = new string[0];
        public float stiffness = 25f;
        [Range(0.5f, 0.98f)] public float damping = 0.8f;
        public float gravity = 2f;
        [Tooltip("Radius of the strand used against the colliders (m).")]
        public float radius = 0.02f;
        [Tooltip("Coat / skirt panels: pushed out of the thighs, off on the Low graphics tier.")]
        public bool coat;
    }

    /// <summary>A sphere on a bone that spring chains cannot enter (head, neck, chest, shoulders).</summary>
    [Serializable]
    public sealed class SpringColliderDef
    {
        public string bone;
        [Tooltip("Centre in the bone's frame (m).")]
        public Vector3 offset;
        public float radius = 0.08f;
    }

    /// <summary>
    /// One facial expression of a blend-shape face (VRM presets: blink, happy, angry, sad, relaxed, surprised, aa, ih,
    /// ou, ee, oh): the blend shapes it moves and their weights (0..1).
    /// </summary>
    [Serializable]
    public sealed class FaceShapeDef
    {
        public string preset;
        public string[] shapes = new string[0];
        public float[] weights = new float[0];
    }

    /// <summary>
    /// What a skinned character looks like: its runtime prefab (skinned meshes, skeleton, Animator with the humanoid
    /// Avatar), the facial setup and the supernatural energy colour. One asset per character, loaded by
    /// <see cref="SkinnedCharacterLoader"/> from Resources/WarOfNyx/Characters/{NAME}.
    /// </summary>
    [CreateAssetMenu(menuName = "War of Nyx/Character Visual Profile")]
    public sealed class CharacterVisualProfile : ScriptableObject
    {
        public string characterName = "KAI";
        public GameObject prefab;
        public CharacterAnimationProfile animation;
        public Color energyColor = new Color(0.62f, 0.25f, 1f);
        [Tooltip("Height of the head centre above the feet (character preview framing).")]
        public float headHeight = 1.69f;
        [Tooltip("Submesh index of the painted face on the skinned renderers (-1: no painted face).")]
        public int faceSubmesh = 1;
        [Tooltip("Blend-shape face (imported VRM / artist models): expressions driven by CharacterFacialAnimator.")]
        public FaceShapeDef[] faceShapes = new FaceShapeDef[0];
        [Tooltip("Hair / coat chains of an imported model (the procedural characters use their fixed helper bones).")]
        public SpringChainDef[] springChains = new SpringChainDef[0];
        public SpringColliderDef[] springColliders = new SpringColliderDef[0];
        [Tooltip("Origin of the art: Procedural (generated by the setup step) or Imported (artist-made FBX / VRM / glTF).")]
        public string artSource = "Procedural";
        [Tooltip("Attribution shown on the CHARACTERS screen (required by CC-BY licences): title, author, licence, source.")]
        public string credit = string.Empty;
        [Tooltip("When the model replaces a roster look: description lines shown instead of the roster's (empty = roster text).")]
        public string titleOverride = string.Empty;
        public string storyOverride = string.Empty;
        public string[] gearOverride = new string[0];

        public bool HasBlendShapeFace => faceShapes != null && faceShapes.Length > 0;
    }
}
